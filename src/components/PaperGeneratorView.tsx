import React, { useState, useEffect } from 'react';
import {
  Student,
  WrongQuestion,
  Question,
  GeneratedPaper,
  PaperSettings,
  QuestionSnapshot,
  PRIMARY_GRADES,
  JUNIOR_GRADES,
  SENIOR_GRADES,
  ALL_GRADES,
  SUBJECT_MAP,
  SubjectKey,
} from '../types';
import {
  Printer,
  Download,
  Save,
  Check,
  RefreshCw,
  FileText,
  ArrowLeft,
  Settings2,
  ShoppingBag,
  Sparkles,
  Columns2,
  Table,
  CheckSquare,
  FileDown,
  Trash2,
  HelpCircle,
  Home,
  Users,
} from 'lucide-react';
import { getQuestionBasket, addBatchToBasket } from '../services/jyeooService';

interface PaperGeneratorViewProps {
  students: Student[];
  wrongQuestions: WrongQuestion[];
  questions: Question[];
  initialStudentId?: string;
  onSavePaper: (paper: Omit<GeneratedPaper, 'id' | 'createdAt' | 'totalScore'>) => void;
  savedPapers: GeneratedPaper[];
  onDeleteSavedPaper: (id: string) => void;
}

export const PaperGeneratorView: React.FC<PaperGeneratorViewProps> = ({
  students,
  wrongQuestions,
  questions,
  initialStudentId,
  onSavePaper,
  savedPapers,
  onDeleteSavedPaper,
}) => {
  // 组卷模式：'basket' (试题篮手工组卷) | 'jyeoo_auto' (智能一键组卷) | 'wrong' (错题针对性重组卷) | 'bank' (题库自选)
  const basketItems = getQuestionBasket();
  const [selectedMode, setSelectedMode] = useState<'basket' | 'jyeoo_auto' | 'wrong' | 'bank'>(
    basketItems.length > 0 ? 'basket' : 'wrong'
  );

  const [selectedStudentId, setSelectedStudentId] = useState<string>(
    initialStudentId || students[0]?.id || ''
  );
  const [bankGradeFilter, setBankGradeFilter] = useState<string>('all');
  const [onlyOpen, setOnlyOpen] = useState(true);

  // 智能组卷参数
  const [autoSubject, setAutoSubject] = useState<SubjectKey>('math');
  const [autoGrade, setAutoGrade] = useState<string>('初二（八年级）');
  const [autoTargetScore, setAutoTargetScore] = useState<number>(100);
  const [autoDifficulty, setAutoDifficulty] = useState<number>(3);

  // 勾选的试题集合
  const [selectedItemIds, setSelectedItemIds] = useState<Set<string>>(new Set());

  // 试卷高级排版设置
  const currentStudent = students.find(s => s.id === selectedStudentId);
  const [settings, setSettings] = useState<PaperSettings>({
    title: currentStudent
      ? (currentStudent.isFamilyChild
          ? `${currentStudent.familyRelation || currentStudent.name}·专属周末巩固测验卷`
          : `${currentStudent.name}·错题强化专练重做卷`)
      : '2026学年中小学学科综合诊断测试卷',
    subtitle: '立足教材考点 · 查漏补缺针对性提高 · 菁优网标准排版',
    header: '注意事项：1. 答题前请将密封线内的项目填写清楚；2. 请将答案规范书写在答题区域；3. 考试结束请仔细核验。',
    footer: '菁优网智能教学工作台 · 命题组卷中心',
    perScore: 10,
    showAnswer: true,
    layoutMode: 'double', // 菁优网专业双栏排版
    showAnswerSheet: true, // 客观题答题卡
    showScoreTable: true, // 大题评分表格
    showSealingLine: true, // 考务密封线
    studentName: currentStudent?.name || '',
    className: currentStudent?.className || '',
    duration: 90,
    examDate: new Date().toISOString().slice(0, 10),
  });

  const [activeTab, setActiveTab] = useState<'config' | 'preview' | 'history'>('config');
  const [savedSuccess, setSavedSuccess] = useState(false);

  // 监听学生切换
  const handleStudentChange = (stuId: string) => {
    setSelectedStudentId(stuId);
    const stu = students.find(s => s.id === stuId);
    if (stu) {
      setSettings(prev => ({
        ...prev,
        title: stu.isFamilyChild
          ? `${stu.familyRelation || stu.name}·专属周末巩固测验卷`
          : `${stu.name}·错题强化专练重做卷`,
        studentName: stu.name,
        className: stu.className,
      }));
    }
  };

  // 候选错题
  const candidateWrongQuestions = wrongQuestions.filter(w => {
    const matchStu = !selectedStudentId || w.studentId === selectedStudentId;
    const matchOpen = !onlyOpen || !w.mastered;
    return matchStu && matchOpen;
  });

  // 候选题库试题
  const candidateBankQuestions = questions.filter(q => {
    if (bankGradeFilter === 'all') return true;
    return q.grade === bankGradeFilter || q.grade.includes(bankGradeFilter);
  });

  // 智能组卷自动生成试题池
  const getAutoGeneratedItems = (): QuestionSnapshot[] => {
    let pool = questions.filter(q => q.subject === autoSubject);
    if (pool.length < 8) pool = questions;
    const count = autoTargetScore >= 120 ? 12 : 10;
    return pool.slice(0, count).map(q => ({
      subject: q.subject,
      grade: q.grade,
      stem: q.stem,
      options: q.options,
      answer: q.answer,
      explanation: q.explanation,
      difficulty: q.difficulty,
      source: q.source,
      kp: q.kp,
    }));
  };

  // 提取最终入卷试题
  const finalItems: QuestionSnapshot[] = (() => {
    if (selectedMode === 'basket') {
      const currentBasket = getQuestionBasket();
      return currentBasket
        .filter(b => selectedItemIds.size === 0 || selectedItemIds.has(b.id))
        .map(b => b.question);
    }
    if (selectedMode === 'jyeoo_auto') {
      return getAutoGeneratedItems();
    }
    if (selectedMode === 'wrong') {
      return candidateWrongQuestions
        .filter(w => selectedItemIds.size === 0 || selectedItemIds.has(w.id))
        .map(w => w.snap);
    }
    return candidateBankQuestions
      .filter(q => selectedItemIds.size === 0 || selectedItemIds.has(q.id))
      .map(q => q);
  })();

  const totalScore = (settings.perScore || 10) * (finalItems.length || 1);

  // 打印试卷
  const handlePrint = () => {
    window.print();
  };

  // 导出专业 Word (.doc) 格式试卷
  const handleDownloadWord = () => {
    const isDouble = settings.layoutMode === 'double';
    const docContent = `<!DOCTYPE html>
<html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
<head>
  <meta charset="utf-8">
  <title>${settings.title}</title>
  <!--[if gte mso 9]>
  <xml>
    <w:WordDocument>
      <w:View>Print</w:View>
      <w:Zoom>100</w:Zoom>
      <w:DoNotOptimizeForBrowser/>
    </w:WordDocument>
  </xml>
  <![endif]-->
  <style>
    body { font-family: 'SimSun', '宋体', 'Times New Roman', serif; line-height: 1.6; font-size: 11pt; color: #000; }
    .header { text-align: center; margin-bottom: 20px; }
    .title { font-size: 18pt; font-weight: bold; margin-bottom: 6px; font-family: 'SimHei', '黑体'; }
    .subtitle { font-size: 11pt; color: #444; }
    .meta-table { width: 100%; border-collapse: collapse; margin-bottom: 15px; text-align: center; font-size: 10pt; }
    .meta-table td, .meta-table th { border: 1px solid #000; padding: 4px 8px; }
    .sealing { font-size: 10pt; border-bottom: 2px dashed #000; padding-bottom: 8px; margin-bottom: 15px; }
    .item { margin-bottom: 18px; }
    .stem { font-weight: bold; margin-bottom: 6px; }
    .options { margin-left: 20px; }
    .score-table { width: 100%; border-collapse: collapse; margin-bottom: 15px; text-align: center; font-size: 9.5pt; }
    .score-table td, .score-table th { border: 1px solid #000; padding: 4px; }
    .ans-page { page-break-before: always; margin-top: 40px; border-top: 2px dashed #666; padding-top: 20px; }
  </style>
</head>
<body>
  ${settings.showSealingLine ? `
  <div class="sealing">
    【密封线内不要答题】 姓名：${settings.studentName || '________'} &nbsp;&nbsp;&nbsp;&nbsp; 班级：${settings.className || '________'} &nbsp;&nbsp;&nbsp;&nbsp; 准考证号：____________ &nbsp;&nbsp;&nbsp;&nbsp; 座位号：______
  </div>` : ''}

  <div class="header">
    <div class="title">${settings.title}</div>
    <div class="subtitle">${settings.subtitle}</div>
    <div style="font-size: 10pt; margin-top: 5px;">考试时间：${settings.duration || 90}分钟 &nbsp;&nbsp;&nbsp;&nbsp; 满分：${totalScore}分 &nbsp;&nbsp;&nbsp;&nbsp; 日期：${settings.examDate}</div>
  </div>

  ${settings.showScoreTable ? `
  <table class="score-table">
    <tr><th>题号</th><th>一 (选择题)</th><th>二 (填空题)</th><th>三 (解答题)</th><th>总分</th><th>评卷人</th></tr>
    <tr><td>得分</td><td>&nbsp;</td><td>&nbsp;</td><td>&nbsp;</td><td>&nbsp;</td><td>&nbsp;</td></tr>
  </table>` : ''}

  <div style="font-size: 9.5pt; color: #333; margin-bottom: 15px;">${settings.header}</div>

  <div class="content">
    <div style="font-weight: bold; margin-bottom: 10px;">一、单项选择题（本大题共 ${finalItems.length} 小题，每小题 ${settings.perScore} 分，共 ${totalScore} 分）</div>
    ${finalItems.map((it, idx) => `
      <div class="item">
        <div class="stem">${idx + 1}. ${it.stem} (${settings.perScore}分)</div>
        <div class="options">
          ${(it.options || []).map(o => `<div><strong>${o.pos}.</strong> ${o.text}</div>`).join('')}
        </div>
      </div>
    `).join('')}
  </div>

  ${settings.showAnswerSheet ? `
  <div style="page-break-before: always; margin-top: 20px;">
    <div style="text-align: center; font-weight: bold; font-size: 13pt; margin-bottom: 10px;">客观题答题卡（请在各题指定对应区域内填涂）</div>
    <table class="meta-table">
      <tr>${finalItems.map((_, i) => `<th>${i + 1}</th>`).join('')}</tr>
      <tr>${finalItems.map(() => `<td>[A] [B] [C] [D]</td>`).join('')}</tr>
    </table>
  </div>` : ''}

  ${settings.showAnswer ? `
  <div class="ans-page">
    <div style="text-align: center; font-size: 14pt; font-weight: bold; margin-bottom: 15px;">【参考答案与详细试题解析】</div>
    ${finalItems.map((it, idx) => `
      <div style="margin-bottom: 15px; border-bottom: 1px solid #ddd; padding-bottom: 10px;">
        <div><strong>第 ${idx + 1} 题</strong> · 参考答案：<span style="font-weight: bold; color: green;">${it.answer}</span> · 考点：${it.kp?.join('/') || '基础'}</div>
        <div style="font-size: 10pt; color: #444; margin-top: 4px;"><strong>解析：</strong>${it.explanation || '依题意分析推导。'}</div>
      </div>
    `).join('')}
  </div>` : ''}
</body>
</html>`;

    const blob = new Blob([docContent], { type: 'application/msword;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${settings.title || '菁优标准试卷'}.doc`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  // 保存试卷
  const handleSaveToCloud = () => {
    onSavePaper({
      title: settings.title,
      subtitle: settings.subtitle,
      mode: selectedMode,
      studentId: selectedStudentId || undefined,
      studentName: currentStudent?.name,
      items: finalItems,
      settings,
    });
    setSavedSuccess(true);
    setTimeout(() => setSavedSuccess(false), 3000);
  };

  return (
    <div className="space-y-6 animate-in fade-in duration-200 pb-16">
      {/* 顶栏与标签导航 */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 no-print">
        <div>
          <h2 className="text-lg font-bold text-slate-900 flex items-center gap-2">
            <span>菁优网专业命题与智能组卷中心</span>
            <span className="px-2 py-0.5 text-xs font-semibold rounded-full bg-blue-100 text-blue-700">
              双栏专业排版
            </span>
          </h2>
          <p className="text-xs text-slate-500 mt-0.5">
            支持试题篮手工组卷、智能一键自动组卷及错题巩固专练，生成符合中高考规范的双栏试卷、密封线与答题卡
          </p>
        </div>

        <div className="flex items-center gap-2">
          <div className="flex items-center bg-white p-1 rounded-xl border border-slate-200 text-xs font-semibold shadow-xs">
            <button
              onClick={() => setActiveTab('config')}
              className={`px-3 py-1.5 rounded-lg transition-colors ${
                activeTab === 'config' ? 'bg-blue-600 text-white shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              组卷与选样
            </button>
            <button
              onClick={() => setActiveTab('preview')}
              className={`px-3 py-1.5 rounded-lg transition-colors ${
                activeTab === 'preview' ? 'bg-blue-600 text-white shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              试卷排版预览 ({finalItems.length}题)
            </button>
            <button
              onClick={() => setActiveTab('history')}
              className={`px-3 py-1.5 rounded-lg transition-colors ${
                activeTab === 'history' ? 'bg-blue-600 text-white shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              已生成试卷 ({savedPapers.length})
            </button>
          </div>
        </div>
      </div>

      {/* 1. 组卷与选样配置 */}
      {activeTab === 'config' && (
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-6 no-print">
          {/* 左侧：组卷模式选择与试题池 (2/3) */}
          <div className="lg:col-span-2 space-y-4">
            {/* 四大组卷模式选项卡 */}
            <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs space-y-3">
              <span className="text-xs font-bold text-slate-700">选择组卷模式：</span>
              <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 text-xs">
                {/* 模式 1: 组卷篮 */}
                <button
                  onClick={() => setSelectedMode('basket')}
                  className={`p-3 rounded-xl border text-left transition-all ${
                    selectedMode === 'basket'
                      ? 'bg-blue-50/80 border-blue-500 ring-2 ring-blue-400/30 text-blue-900'
                      : 'border-slate-200 hover:bg-slate-50 text-slate-700'
                  }`}
                >
                  <div className="flex items-center justify-between font-bold">
                    <span>🛒 组卷篮组卷</span>
                    <span className="text-[10px] bg-blue-100 text-blue-700 px-1.5 py-0.5 rounded-full font-mono">
                      {basketItems.length}
                    </span>
                  </div>
                  <p className="text-[11px] text-slate-500 mt-1">从题库或试卷中手工挑选的题目</p>
                </button>

                {/* 模式 2: 智能一键组卷 */}
                <button
                  onClick={() => setSelectedMode('jyeoo_auto')}
                  className={`p-3 rounded-xl border text-left transition-all ${
                    selectedMode === 'jyeoo_auto'
                      ? 'bg-blue-50/80 border-blue-500 ring-2 ring-blue-400/30 text-blue-900'
                      : 'border-slate-200 hover:bg-slate-50 text-slate-700'
                  }`}
                >
                  <div className="flex items-center justify-between font-bold">
                    <span>⚡ 智能一键组卷</span>
                    <Sparkles className="w-3.5 h-3.5 text-blue-600" />
                  </div>
                  <p className="text-[11px] text-slate-500 mt-1">按学科、难度与分值自动出卷</p>
                </button>

                {/* 模式 3: 错题重做卷 */}
                <button
                  onClick={() => setSelectedMode('wrong')}
                  className={`p-3 rounded-xl border text-left transition-all ${
                    selectedMode === 'wrong'
                      ? 'bg-rose-50/80 border-rose-500 ring-2 ring-rose-400/30 text-rose-900'
                      : 'border-slate-200 hover:bg-slate-50 text-slate-700'
                  }`}
                >
                  <div className="flex items-center justify-between font-bold">
                    <span>📖 错题针对巩固</span>
                    <Home className="w-3.5 h-3.5 text-rose-500" />
                  </div>
                  <p className="text-[11px] text-slate-500 mt-1">自家小孩或学生未掌握错题</p>
                </button>

                {/* 模式 4: 题库自选 */}
                <button
                  onClick={() => setSelectedMode('bank')}
                  className={`p-3 rounded-xl border text-left transition-all ${
                    selectedMode === 'bank'
                      ? 'bg-blue-50/80 border-blue-500 ring-2 ring-blue-400/30 text-blue-900'
                      : 'border-slate-200 hover:bg-slate-50 text-slate-700'
                  }`}
                >
                  <div className="flex items-center justify-between font-bold">
                    <span>📚 题库自选题</span>
                    <FileText className="w-3.5 h-3.5 text-slate-500" />
                  </div>
                  <p className="text-[11px] text-slate-500 mt-1">浏览全部精选题并勾选入卷</p>
                </button>
              </div>
            </div>

            {/* 智能一键组卷专属参数卡 */}
            {selectedMode === 'jyeoo_auto' && (
              <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs space-y-3 text-xs">
                <div className="flex items-center gap-2 font-bold text-slate-800">
                  <Sparkles className="w-4 h-4 text-blue-600" />
                  <span>菁优智能组卷规格设定</span>
                </div>
                <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
                  <div>
                    <label className="block text-slate-500 mb-1 font-medium">考试学科</label>
                    <select
                      value={autoSubject}
                      onChange={e => setAutoSubject(e.target.value as SubjectKey)}
                      className="w-full px-3 py-1.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800"
                    >
                      {Object.entries(SUBJECT_MAP).map(([k, label]) => (
                        <option key={k} value={k}>{label}</option>
                      ))}
                    </select>
                  </div>
                  <div>
                    <label className="block text-slate-500 mb-1 font-medium">适用年级</label>
                    <select
                      value={autoGrade}
                      onChange={e => setAutoGrade(e.target.value)}
                      className="w-full px-3 py-1.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800"
                    >
                      {ALL_GRADES.map(g => (
                        <option key={g} value={g}>{g}</option>
                      ))}
                    </select>
                  </div>
                  <div>
                    <label className="block text-slate-500 mb-1 font-medium">试卷满分</label>
                    <select
                      value={autoTargetScore}
                      onChange={e => setAutoTargetScore(Number(e.target.value))}
                      className="w-full px-3 py-1.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 font-bold"
                    >
                      <option value={100}>100 分 (标准卷)</option>
                      <option value={120}>120 分 (中考标准卷)</option>
                      <option value={150}>150 分 (高考标准卷)</option>
                    </select>
                  </div>
                  <div>
                    <label className="block text-slate-500 mb-1 font-medium">难度梯度</label>
                    <select
                      value={autoDifficulty}
                      onChange={e => setAutoDifficulty(Number(e.target.value))}
                      className="w-full px-3 py-1.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800"
                    >
                      <option value={2}>基础过关 (低难度)</option>
                      <option value={3}>中等适中 (期中期末)</option>
                      <option value={4}>压轴拔高 (中考一模)</option>
                    </select>
                  </div>
                </div>
              </div>
            )}

            {/* 错题模式专属选择学生卡 (严格区分自家小孩 vs 班级在校生) */}
            {selectedMode === 'wrong' && (
              <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs space-y-3 text-xs">
                <div className="flex items-center justify-between">
                  <span className="font-bold text-slate-800">选择巩固对象（自家小孩 / 班级在校生）：</span>
                  <label className="flex items-center gap-1.5 cursor-pointer text-slate-600">
                    <input
                      type="checkbox"
                      checked={onlyOpen}
                      onChange={e => setOnlyOpen(e.target.checked)}
                      className="rounded text-blue-600"
                    />
                    <span>仅包含未攻克薄弱题</span>
                  </label>
                </div>

                <select
                  value={selectedStudentId}
                  onChange={e => handleStudentChange(e.target.value)}
                  className="w-full px-3 py-2 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 font-medium"
                >
                  <optgroup label="🏠 我家小孩专属专档">
                    {students.filter(s => s.isFamilyChild).map(s => (
                      <option key={s.id} value={s.id}>
                        ★ {s.familyRelation || '我家孩子'} · {s.name} ({s.grade})
                      </option>
                    ))}
                  </optgroup>
                  <optgroup label="👥 班级在校学生">
                    {students.filter(s => !s.isFamilyChild).map(s => (
                      <option key={s.id} value={s.id}>
                        {s.name} ({s.className} · {s.grade})
                      </option>
                    ))}
                  </optgroup>
                </select>
              </div>
            )}

            {/* 试题候选与勾选列表 */}
            <div className="bg-white rounded-xl border border-slate-200 shadow-xs p-4 space-y-3">
              <div className="flex items-center justify-between text-xs text-slate-600 pb-2 border-b border-slate-100">
                <span className="font-bold text-slate-800">
                  当前入选候选试题 ({finalItems.length} 题 · 满分 {totalScore} 分)
                </span>
                <span className="text-[11px] text-slate-400">
                  {selectedMode === 'basket' && '已加载组卷篮题目'}
                  {selectedMode === 'jyeoo_auto' && '已根据规格自动拼装'}
                  {selectedMode === 'wrong' && '已提取该学生错题本快照'}
                </span>
              </div>

              {finalItems.length === 0 ? (
                <div className="py-12 text-center text-slate-400 text-xs space-y-3">
                  <p>暂无匹配题目，可先在【菁优题库与试卷】中挑选题目加入组卷篮，或点击下方快速装入：</p>
                  <button
                    type="button"
                    onClick={() => {
                      addBatchToBasket(questions.slice(0, 8), 'bank');
                      window.location.reload();
                    }}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-blue-600 hover:bg-blue-700 text-white font-semibold transition-colors"
                  >
                    <Sparkles className="w-3.5 h-3.5" />
                    <span>⚡ 一键将题库 8 道精选题装入组卷篮</span>
                  </button>
                </div>
              ) : (
                <div className="space-y-3 max-h-[500px] overflow-y-auto pr-1">
                  {finalItems.map((q, idx) => (
                    <div
                      key={idx}
                      className="p-3 bg-slate-50/70 hover:bg-slate-50 rounded-xl border border-slate-200/80 text-xs space-y-1.5 transition-colors"
                    >
                      <div className="flex items-center justify-between text-[11px] text-slate-500">
                        <span className="font-bold text-blue-700">第 {idx + 1} 题</span>
                        <div className="flex items-center gap-2">
                          <span>{q.source || '试题'}</span>
                          <span>·</span>
                          <span className="text-emerald-700 font-mono font-bold">答案: {q.answer}</span>
                        </div>
                      </div>
                      <div className="text-slate-800 line-clamp-2 leading-relaxed">
                        {q.stem}
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </div>
          </div>

          {/* 右侧：菁优网专业排版设定与操作 (1/3) */}
          <div className="space-y-4">
            <div className="bg-white rounded-xl border border-slate-200 shadow-xs p-5 space-y-4 text-xs">
              <div className="flex items-center gap-2 pb-2 border-b border-slate-100 font-bold text-slate-900">
                <Settings2 className="w-4 h-4 text-blue-600" />
                <span>菁优网专业试卷排版设置</span>
              </div>

              {/* 双栏 / 单栏切换 */}
              <div className="space-y-1.5">
                <label className="font-semibold text-slate-700 flex items-center gap-1.5">
                  <Columns2 className="w-3.5 h-3.5 text-blue-600" />
                  <span>试卷排版版式</span>
                </label>
                <div className="grid grid-cols-2 gap-2">
                  <button
                    type="button"
                    onClick={() => setSettings({ ...settings, layoutMode: 'double' })}
                    className={`py-2 px-3 rounded-lg border font-semibold text-center transition-all ${
                      settings.layoutMode === 'double'
                        ? 'bg-blue-600 text-white border-blue-600 shadow-xs'
                        : 'border-slate-200 hover:bg-slate-50 text-slate-700'
                    }`}
                  >
                    菁优专业双栏排版
                  </button>
                  <button
                    type="button"
                    onClick={() => setSettings({ ...settings, layoutMode: 'single' })}
                    className={`py-2 px-3 rounded-lg border font-semibold text-center transition-all ${
                      settings.layoutMode === 'single'
                        ? 'bg-blue-600 text-white border-blue-600 shadow-xs'
                        : 'border-slate-200 hover:bg-slate-50 text-slate-700'
                    }`}
                  >
                    标准单栏排版
                  </button>
                </div>
              </div>

              {/* 试卷标题 */}
              <div>
                <label className="font-semibold text-slate-700 block mb-1">试卷大标题</label>
                <input
                  type="text"
                  value={settings.title}
                  onChange={e => setSettings({ ...settings, title: e.target.value })}
                  className="w-full px-3 py-2 border border-slate-200 rounded-lg text-slate-800 font-bold"
                />
              </div>

              {/* 试卷副标题 */}
              <div>
                <label className="font-semibold text-slate-700 block mb-1">副标题</label>
                <input
                  type="text"
                  value={settings.subtitle}
                  onChange={e => setSettings({ ...settings, subtitle: e.target.value })}
                  className="w-full px-3 py-2 border border-slate-200 rounded-lg"
                />
              </div>

              {/* 考试时长与每题分值 */}
              <div className="grid grid-cols-2 gap-2">
                <div>
                  <label className="font-semibold text-slate-700 block mb-1">考试时长 (分钟)</label>
                  <input
                    type="number"
                    value={settings.duration || 90}
                    onChange={e => setSettings({ ...settings, duration: Number(e.target.value) })}
                    className="w-full px-3 py-2 border border-slate-200 rounded-lg"
                  />
                </div>
                <div>
                  <label className="font-semibold text-slate-700 block mb-1">每题分值</label>
                  <input
                    type="number"
                    value={settings.perScore || 10}
                    onChange={e => setSettings({ ...settings, perScore: Number(e.target.value) })}
                    className="w-full px-3 py-2 border border-slate-200 rounded-lg"
                  />
                </div>
              </div>

              {/* 标准考务开关 */}
              <div className="space-y-2 pt-2 border-t border-slate-100">
                <label className="flex items-center gap-2 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={Boolean(settings.showSealingLine)}
                    onChange={e => setSettings({ ...settings, showSealingLine: e.target.checked })}
                    className="rounded text-blue-600"
                  />
                  <span>生成考务密封线（姓名/准考证号/考场）</span>
                </label>

                <label className="flex items-center gap-2 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={Boolean(settings.showScoreTable)}
                    onChange={e => setSettings({ ...settings, showScoreTable: e.target.checked })}
                    className="rounded text-blue-600"
                  />
                  <span>生成大题得分统计评分表</span>
                </label>

                <label className="flex items-center gap-2 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={Boolean(settings.showAnswerSheet)}
                    onChange={e => setSettings({ ...settings, showAnswerSheet: e.target.checked })}
                    className="rounded text-blue-600"
                  />
                  <span>生成客观题标准答题卡</span>
                </label>

                <label className="flex items-center gap-2 cursor-pointer">
                  <input
                    type="checkbox"
                    checked={Boolean(settings.showAnswer)}
                    onChange={e => setSettings({ ...settings, showAnswer: e.target.checked })}
                    className="rounded text-blue-600"
                  />
                  <span>随卷生成参考答案与试题详细解析页</span>
                </label>
              </div>

              {/* 动作按钮 */}
              <div className="pt-3 border-t border-slate-100 space-y-2">
                <button
                  onClick={() => setActiveTab('preview')}
                  className="w-full flex items-center justify-center gap-2 py-2.5 bg-blue-600 hover:bg-blue-700 text-white font-bold rounded-xl shadow-xs transition-colors"
                >
                  <FileText className="w-4 h-4" />
                  <span>立即生成并预览试卷排版</span>
                </button>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* 2. 试卷排版预览模式 (双栏/单栏即时呈现) */}
      {activeTab === 'preview' && (
        <div className="space-y-6">
          {/* 预览动作控制工具条 */}
          <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-xs flex flex-wrap items-center justify-between gap-3 no-print">
            <button
              onClick={() => setActiveTab('config')}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs text-slate-600 hover:bg-slate-100 rounded-lg transition-colors"
            >
              <ArrowLeft className="w-3.5 h-3.5" />
              <span>返回重新配置</span>
            </button>

            <div className="flex items-center gap-2">
              {/* 版式切换 */}
              <button
                onClick={() => setSettings({ ...settings, layoutMode: settings.layoutMode === 'double' ? 'single' : 'double' })}
                className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-lg transition-colors"
              >
                <Columns2 className="w-3.5 h-3.5 text-blue-600" />
                <span>版式: {settings.layoutMode === 'double' ? '双栏排版' : '单栏排版'}</span>
              </button>

              {/* 导出 Word */}
              <button
                onClick={handleDownloadWord}
                className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-blue-700 bg-blue-50 hover:bg-blue-100 rounded-lg transition-colors"
                title="导出标准格式 Word (.doc) 文档"
              >
                <FileDown className="w-3.5 h-3.5" />
                <span>导出 Word 文档</span>
              </button>

              {/* 打印 */}
              <button
                onClick={handlePrint}
                className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-bold text-white bg-blue-600 hover:bg-blue-700 rounded-lg shadow-xs transition-colors"
              >
                <Printer className="w-3.5 h-3.5" />
                <span>打印 / 导出 PDF</span>
              </button>

              {/* 保存到云端 */}
              <button
                onClick={handleSaveToCloud}
                className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-emerald-700 bg-emerald-50 hover:bg-emerald-100 rounded-lg transition-colors"
              >
                {savedSuccess ? <Check className="w-3.5 h-3.5" /> : <Save className="w-3.5 h-3.5" />}
                <span>{savedSuccess ? '已存入试卷库' : '存入试卷库'}</span>
              </button>
            </div>
          </div>

          {/* 试卷实体打印渲染纸张 */}
          <div className="bg-white rounded-2xl border border-slate-200 shadow-lg p-8 sm:p-12 max-w-5xl mx-auto print:p-0 print:border-none print:shadow-none">
            {/* 密封线区域 */}
            {settings.showSealingLine && (
              <div className="border-b-2 border-dashed border-slate-400 pb-3 mb-6 flex items-center justify-between text-xs text-slate-600">
                <span className="font-bold tracking-widest text-slate-800">【密封线内请勿答题】</span>
                <div className="flex items-center gap-6">
                  <span>学校：{currentStudent?.school || '________________'}</span>
                  <span>班级：{settings.className || '____________'}</span>
                  <span>姓名：{settings.studentName || '____________'}</span>
                  <span>考号：________________</span>
                </div>
              </div>
            )}

            {/* 试卷头部标题 */}
            <div className="text-center space-y-1.5 mb-6">
              <h1 className="text-2xl font-extrabold text-slate-900 tracking-tight">
                {settings.title}
              </h1>
              {settings.subtitle && (
                <p className="text-xs text-slate-500 font-medium">
                  {settings.subtitle}
                </p>
              )}
              <div className="text-xs text-slate-600 pt-1 flex items-center justify-center gap-6">
                <span>考试时长：{settings.duration || 90} 分钟</span>
                <span>试卷满分：{totalScore} 分</span>
                <span>考试日期：{settings.examDate}</span>
              </div>
            </div>

            {/* 大题评分汇总表 */}
            {settings.showScoreTable && (
              <div className="mb-6 overflow-x-auto">
                <table className="w-full border-collapse border border-slate-800 text-center text-xs">
                  <thead>
                    <tr className="bg-slate-50">
                      <th className="border border-slate-800 py-1.5 px-3">题号</th>
                      <th className="border border-slate-800 py-1.5 px-3">一 (选择题)</th>
                      <th className="border border-slate-800 py-1.5 px-3">二 (填空题)</th>
                      <th className="border border-slate-800 py-1.5 px-3">三 (解答题)</th>
                      <th className="border border-slate-800 py-1.5 px-3 font-bold">总分</th>
                      <th className="border border-slate-800 py-1.5 px-3">评卷人</th>
                    </tr>
                  </thead>
                  <tbody>
                    <tr>
                      <td className="border border-slate-800 py-2 font-bold">得分</td>
                      <td className="border border-slate-800 py-2"></td>
                      <td className="border border-slate-800 py-2"></td>
                      <td className="border border-slate-800 py-2"></td>
                      <td className="border border-slate-800 py-2"></td>
                      <td className="border border-slate-800 py-2"></td>
                    </tr>
                  </tbody>
                </table>
              </div>
            )}

            {/* 考生须知 */}
            <div className="text-xs text-slate-600 mb-6 bg-slate-50 p-2.5 rounded border border-slate-200/80 leading-relaxed print:bg-white print:border-slate-400">
              <span className="font-bold">考生须知：</span>
              <span>{settings.header}（本卷共 {finalItems.length} 题，每题 {settings.perScore} 分，满分 {totalScore} 分）</span>
            </div>

            {/* 试题列表区 (支持菁优专业双栏排版) */}
            <div className="border-b border-slate-800 pb-1 mb-4 font-bold text-sm text-slate-900">
              一、单项选择题（本大题共 {finalItems.length} 小题，每小题 {settings.perScore} 分，共 {totalScore} 分）
            </div>

            <div className={settings.layoutMode === 'double' ? 'md:columns-2 gap-8' : 'space-y-6'}>
              {finalItems.map((item, idx) => (
                <div key={idx} className="break-inside-avoid mb-6 space-y-2 text-slate-900">
                  <div className="text-sm leading-relaxed">
                    <span className="font-bold mr-1.5">{idx + 1}.</span>
                    <span>{item.stem}</span>
                    <span className="text-xs text-slate-400 ml-1 font-mono">
                      ({settings.perScore}分)
                    </span>
                  </div>

                  {item.options && item.options.length > 0 && (
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-x-4 gap-y-1.5 text-xs ml-4">
                      {item.options.map(opt => (
                        <div key={opt.pos} className="flex items-start gap-1">
                          <span className="font-bold">{opt.pos}.</span>
                          <span>{opt.text}</span>
                        </div>
                      ))}
                    </div>
                  )}
                </div>
              ))}
            </div>

            {/* 客观题标准答题卡 */}
            {settings.showAnswerSheet && (
              <div className="mt-12 pt-6 border-t-2 border-dashed border-slate-400 page-break-before">
                <div className="text-center font-bold text-sm text-slate-900 mb-3">
                  【客观题答题卡】请在对应题号下填涂正确答案选项
                </div>
                <div className="overflow-x-auto">
                  <table className="w-full border-collapse border border-slate-700 text-center text-xs">
                    <thead>
                      <tr className="bg-slate-100">
                        {finalItems.map((_, i) => (
                          <th key={i} className="border border-slate-700 p-1 font-mono">{i + 1}</th>
                        ))}
                      </tr>
                    </thead>
                    <tbody>
                      <tr>
                        {finalItems.map((_, i) => (
                          <td key={i} className="border border-slate-700 p-1.5 text-[11px] font-mono text-slate-400">
                            [A] [B]<br/>[C] [D]
                          </td>
                        ))}
                      </tr>
                    </tbody>
                  </table>
                </div>
              </div>
            )}

            {/* 试卷页脚 */}
            <div className="mt-10 pt-4 border-t border-slate-200 text-center text-xs text-slate-400">
              {settings.footer} · 第 1 页（共 {settings.showAnswer ? 2 : 1} 页）
            </div>

            {/* 答案与解析附页 */}
            {settings.showAnswer && (
              <div className="page-break-before mt-12 pt-8 border-t-2 border-dashed border-slate-400">
                <div className="text-center pb-4 mb-6 border-b border-slate-200">
                  <h2 className="text-lg font-bold text-slate-900">
                    【参考答案与试题详细解析】
                  </h2>
                  <p className="text-xs text-slate-500 mt-0.5">
                    《{settings.title}》官方参考答案及评分规范
                  </p>
                </div>

                <div className="space-y-4 text-xs">
                  {finalItems.map((item, idx) => (
                    <div key={idx} className="break-inside-avoid p-3.5 rounded-xl bg-slate-50 print:bg-white border border-slate-200">
                      <div className="flex items-center gap-2 mb-1.5">
                        <span className="font-bold text-slate-900">第 {idx + 1} 题</span>
                        <span className="text-slate-400">·</span>
                        <span className="font-bold text-emerald-700">
                          标准答案：{item.answer}
                        </span>
                        <span className="text-slate-400">·</span>
                        <span className="text-slate-500">考点：{item.kp?.join(' / ') || '基础综合'}</span>
                      </div>
                      {item.explanation && (
                        <p className="text-slate-600 leading-relaxed whitespace-pre-wrap">
                          <span className="font-semibold text-slate-700">【权威解析】: </span>
                          {item.explanation}
                        </p>
                      )}
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        </div>
      )}

      {/* 3. 历史试卷归档列表 */}
      {activeTab === 'history' && (
        <div className="bg-white rounded-xl border border-slate-200 shadow-xs p-6 space-y-4 no-print">
          <h3 className="text-sm font-semibold text-slate-900">历史已生成试卷归档 ({savedPapers.length})</h3>
          {savedPapers.length === 0 ? (
            <div className="py-12 text-center text-xs text-slate-400">
              暂无已保存的试卷记录
            </div>
          ) : (
            <div className="divide-y divide-slate-100">
              {savedPapers.map(p => (
                <div key={p.id} className="py-4 flex items-center justify-between gap-4">
                  <div>
                    <h4 className="text-sm font-bold text-slate-900">{p.title}</h4>
                    <div className="flex items-center gap-2 text-xs text-slate-500 mt-1">
                      <span>对象：{p.studentName || '通用'}</span>
                      <span>·</span>
                      <span>题量：{p.items?.length || 0} 题</span>
                      <span>·</span>
                      <span>满分：{p.totalScore} 分</span>
                      <span>·</span>
                      <span>创建时间：{new Date(p.createdAt).toLocaleDateString()}</span>
                    </div>
                  </div>

                  <div className="flex items-center gap-2">
                    <button
                      onClick={() => {
                        setSettings(p.settings);
                        setActiveTab('preview');
                      }}
                      className="px-3 py-1.5 text-xs font-semibold text-blue-700 bg-blue-50 hover:bg-blue-100 rounded-lg transition-colors"
                    >
                      重新预览与打印
                    </button>
                    <button
                      onClick={() => onDeleteSavedPaper(p.id)}
                      className="text-xs text-slate-400 hover:text-rose-600 p-1.5 transition-colors"
                      title="删除记录"
                    >
                      删除
                    </button>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  );
};
